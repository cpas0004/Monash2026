-- Creating dimensions

CREATE TABLE BOOKINGMONTHDIM AS
SELECT DISTINCT TO_CHAR(BOOKINGDATE, 'YYYYMM') AS BOOKINGMONTHID,
       TO_CHAR(BOOKINGDATE, 'MM') AS BOOKINGMONTH,
       TO_CHAR(BOOKINGDATE, 'YYYY') AS BOOKINGYEAR
FROM BOOKING;

CREATE TABLE FACULTYDIM AS
SELECT DISTINCT FACULTYID, FACULTYNAME
FROM FACULTY;

CREATE TABLE AGEGROUPDIM (
    AGEGROUPID NUMBER PRIMARY KEY,
    AGEGROUPDESCRIPTION VARCHAR2(50) NOT NULL,
    MINIMUMAGE NUMBER NOT NULL,
    MAXIMUMAGE NUMBER NOT NULL
);

