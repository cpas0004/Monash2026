CREATE TABLE TEMPMAINTENANCEFACT AS
SELECT M.MAINTENANCEID,
    M.MAINTENANCECOST,
    M.MAINTENANCETYPE AS MAINTENANCETYPEID,
    M.TEAMID,
    C.CARBODYTYPE,
    C.NUMSEATS
FROM MAINTENANCE M
JOIN CAR C ON M.REGISTRATIONNO = C.REGISTRATIONNO;

CREATE TABLE MAINTENANCEFACT AS
SELECT TMF.MAINTENANCETYPEID,
    TMF.TEAMID,
    C.CARBODYID,
    COUNT(TMF.MAINTENANCEID) AS NUMBEROFMAINTENANCE,
    SUM(TMF.MAINTENANCECOST) AS TOTALMAINTENANCECOST
FROM TEMPMAINTENANCEFACT TMF
JOIN CARBODYDIM C ON TMF.CARBODYTYPE = C.CARBODYTYPE AND TMF.NUMSEATS = C.NUMSEATS
GROUP BY TMF.MAINTENANCETYPEID, TMF.TEAMID, C.CARBODYID;

