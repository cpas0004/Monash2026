FROM MAINTENANCETYPE;

CREATE TABLE RESEARCHCENTERDIM AS
SELECT DISTINCT CENTERID, CENTERNAME
FROM RESEARCHCENTER;

CREATE TABLE TEAMCENTERBRIDGE AS
SELECT DISTINCT TEAMID, CENTERID
FROM BELONGTO;

CREATE TABLE MAINTENANCETEAMDIM AS
SELECT MT.TEAMID,
    LISTAGG(BT.CENTERID, '_') WITHIN GROUP (ORDER BY BT.CENTERID) AS CENTERGROUPLIST,
    COUNT(BT.CENTERID) AS CENTERCOUNT,
    1.0/COUNT(BT.CENTERID) AS CENTERWEIGHTFACTOR
FROM MAINTENANCETEAM MT JOIN (SELECT DISTINCT TEAMID, CENTERID FROM BELONGTO) BT ON MT.TEAMID = BT.TEAMID
GROUP BY MT.TEAMID;

SELECT * FROM BELONGTO
ORDER BY TEAMID, CENTERID;

