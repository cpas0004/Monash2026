CREATE TABLE CARBODYDIM AS
SELECT ROW_NUMBER() OVER (ORDER BY CARBODYTYPE) AS CARBODYID,
    CARBODYTYPE,
    NUMSEATS
FROM
(
    SELECT DISTINCT CARBODYTYPE, NUMSEATS
    FROM CAR
);

CREATE TABLE MAINTENANCETYPEDIM AS
