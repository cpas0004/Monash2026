-- BookingFact table

CREATE TABLE TEMPBOOKINGFACT AS
SELECT B.BOOKINGID,
    TO_CHAR(B.BOOKINGDATE, 'YYYYMM') AS BOOKINGMONTHID,
    P.FACULTYID,
    P.PASSENGERAGE,
    C.CARBODYTYPE,
    C.NUMSEATS
FROM BOOKING B
JOIN PASSENGER P ON B.PASSENGERID = P.PASSENGERID
JOIN CAR C ON B.REGISTRATIONNO = C.REGISTRATIONNO;

CREATE TABLE BOOKINGFACT AS
SELECT TBF.BOOKINGMONTHID,
    TBF.FACULTYID,
    AG.AGEGROUPID,
    CB.CARBODYID,
    COUNT(TBF.BOOKINGID) AS NUMBEROFBOOKINGS
FROM TEMPBOOKINGFACT TBF
JOIN AGEGROUPDIM AG ON TBF.PASSENGERAGE >= AG.MINIMUMAGE AND TBF.PASSENGERAGE <= AG.MAXIMUMAGE
JOIN CARBODYDIM CB ON TBF.CARBODYTYPE = CB.CARBODYTYPE AND TBF.NUMSEATS = CB.NUMSEATS
GROUP BY TBF.BOOKINGMONTHID, TBF.FACULTYID, AG.AGEGROUPID, CB.CARBODYID;

