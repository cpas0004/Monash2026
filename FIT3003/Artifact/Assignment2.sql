-- AccidentFact table

CREATE TABLE TEMPACCIDENTFACT AS
SELECT AI.ACCIDENTID,
    CA.REGISTRATIONNO,
    AI.ACCIDENTZONE AS ZONEID,
    AI.ERRORCODE,
    AI.CAR_DAMAGE_SEVERITY
FROM ACCIDENTINFO AI
JOIN CARACCIDENT CA ON AI.ACCIDENTID = CA.ACCIDENTID;


CREATE TABLE ACCIDENTFACT AS
SELECT TAF.REGISTRATIONNO,
    TAF.ZONEID,
    DS.DAMAGESEVERITYID,
    TAF.ERRORCODE,
    COUNT(TAF.ACCIDENTID) AS NUMBEROFACCIDENTS
FROM TEMPACCIDENTFACT TAF
JOIN DAMAGESEVERITYDIM DS ON TAF.CAR_DAMAGE_SEVERITY = DS.DESCRIPTION
GROUP BY TAF.REGISTRATIONNO, TAF.ZONEID, DS.DAMAGESEVERITYID, TAF.ERRORCODE;

